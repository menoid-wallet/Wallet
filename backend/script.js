// =====================================================
// MAIN
// =====================================================

async function main() {

  const poseidon =
    await circomlibjs.buildPoseidon();

  const hash = (inputs) => {

    return BigInt(
      poseidon.F.toString(
        poseidon(inputs)
      )
    );
  };

  const tree =
    new IncrementalMerkleTree(
      hash,
      20,
      0n,
      2
    );

  let output = "";

  for (let i = 0; i < commitments.length; i++) {

    const commitment =
      BigInt(commitments[i]);

    tree.insert(commitment);

    const root =
      BigInt(tree.root).toString();

    output += `${i}\n"${root}"\n\n`;
  }

  // =====================================================
  // WRITE FILE
  // =====================================================

  fs.writeFileSync(
    "roots.txt",
    output
  );

  console.log(
    "\nroots.txt generated\n"
  );
}

main().catch(console.error);